"""Figures and tables for the DGTD arms on B2/B3 (ho_bench.py), optionally
with the baseline arms of studies/benchmarks (same record format)."""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

HERE = Path(__file__).resolve().parent
FIG = HERE / "figures"
BASE = HERE.parent / "benchmarks" / "data"


def load(folder):
    recs = []
    for f in sorted(Path(folder).glob("*.json")):
        r = json.loads(f.read_text())
        if "metrics" in r:
            recs.append(r)
    return recs


def label(arm):
    if arm.startswith("dg"):
        p = arm[2]
        return f"Wakis DGTD p={p} ({'straight-sided' if 'straight' in arm else 'curved'})"
    return f"Wakis FIT ({arm})"


def main_plot(phase):
    FIG.mkdir(exist_ok=True)
    recs = load(HERE / "data" / phase) + (load(BASE / phase) if (BASE / phase).exists() else [])
    if not recs:
        return
    cases = sorted({r["case"] for r in recs})
    metrics = ["q_ext_nrms"] + (["enh_peak"] if phase == "B3" else ["q_ext_height"])
    fig, axs = plt.subplots(len(metrics), len(cases), figsize=(4.2 * len(cases), 3.8 * len(metrics)),
                            squeeze=False)  # fmt: skip
    lines = [f"# {phase}: DGTD arms (generated by plot_bench_ho.py)", "",
             "| case | arm | h [nm] | unknowns | steps | run [s] | " + " | ".join(metrics) + " |",
             "|---|---|---|---|---|---|" + "---|" * len(metrics)]  # fmt: skip
    for j, case in enumerate(cases):
        arms = sorted({r["arm"] for r in recs if r["case"] == case})
        for k, arm in enumerate(arms):
            rs = sorted([r for r in recs if r["case"] == case and r["arm"] == arm],
                        key=lambda r: r["cost"]["unknowns"])  # fmt: skip
            for i, m in enumerate(metrics):
                y = [abs(r["metrics"].get(m) or np.nan) * 100 for r in rs]
                x = [r["cost"]["unknowns"] for r in rs]
                axs[i, j].loglog(x, y, marker="osD^v<>"[k % 7],
                                 ls="-" if arm.startswith("dg") else "--", label=label(arm))  # fmt: skip
            for r in rs:
                c = r["cost"]
                vals = " | ".join(f"{abs(r['metrics'].get(m) or np.nan) * 100:.3f} %" for m in metrics)
                lines.append(f"| {case} | {arm} | {r['resolution'] * 1e9:.2f} | {c['unknowns']:,} | "
                             f"{c['steps']} | {c['run_s']:.0f} | {vals} |")  # fmt: skip
        for i, m in enumerate(metrics):
            axs[i, j].set_title(f"{case}: {m}")
            axs[i, j].set_xlabel("field unknowns")
            axs[i, j].set_ylabel("error [%]")
            axs[i, j].grid(True, which="both", alpha=0.2)
    axs[0, 0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(FIG / f"{phase}_error_vs_unknowns.png", dpi=130)
    plt.close(fig)
    (HERE / "data" / phase / "summary.md").write_text("\n".join(lines) + "\n")
