"""Figures and tables for the DGTD arms on B2/B3 (ho_bench.py), optionally
with the baseline arms of studies/benchmarks (same record format)."""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

HERE = Path(__file__).resolve().parent
FIG = HERE / "figures"
BASE = HERE / "baseline_store"
BASE_ARMS = (
    "tri-uniform",
    "tri-graded",
    "tri-graded-pml",
    "cart-conformal-all-graded",
    "hybrid-quadtri",
    "subgrid-2to1",
)
TARGETS = {
    "B2": [("q_ext_nrms", 0.01), ("q_ext_nrms", 0.001)],
    "B3": [("enh_peak", 0.05), ("enh_peak", 0.02), ("q_ext_nrms", 0.01)],
}


def load(folder, unstable=None):
    recs = []
    for f in sorted(Path(folder).glob("*.json")):
        r = json.loads(f.read_text())
        if "metrics" not in r:
            continue
        if r.get("arm", "").startswith("dg") and (
            not np.isfinite(r["metrics"].get("q_ext_nrms", np.nan))
            or abs(r["metrics"]["q_ext_nrms"]) > 0.2
        ):
            if unstable is not None:
                unstable.append(r)
            continue
        recs.append(r)
    return recs


def load_baselines(phase):
    recs = []
    if not BASE.exists():
        return recs
    for f in sorted(BASE.glob(f"{phase}*/*/*.json")):
        r = json.loads(f.read_text())
        if (
            r.get("arm") in BASE_ARMS
            and not r.get("arm", "").startswith("dgtd-")
            and "metrics" in r
            and (r.get("window_factor") or 1) == 1
        ):
            recs.append(r)
    return recs


def label(arm):
    if arm.startswith("dg"):
        p = arm[2]
        return f"Wakis DGTD p={p} ({'straight-sided' if 'straight' in arm else 'curved'})"
    return f"Wakis FIT ({arm})"


def _fmt_cost(v, spec):
    if not np.isfinite(v):
        return "—"
    return ("≤ " if v < 0 else "") + spec.format(abs(v))


def write_cost_to_target(phase, recs, cases):
    from wakis.benchmarks.runner import cost_to_target

    mtgts = TARGETS.get(phase, [("q_ext_nrms", 0.01)])
    lines = [
        f"# {phase}: cost to target (generated by plot_bench_ho.py)",
        "",
        "Log-log interpolated cost from which the error stays at or below target "
        "(`≤` = coarsest run already meets target; `—` = target not reached).",
        "",
        "| case | metric | target | arm | unknowns | work (unknowns × steps) | run [s] |",
        "|---|---|---|---|---|---|---|",
    ]
    for case in cases:
        arms = sorted({r["arm"] for r in recs if r["case"] == case})
        for metric, target in mtgts:
            for arm in arms:
                rs = []
                for r in recs:
                    if (
                        r["case"] == case
                        and r["arm"] == arm
                        and r["metrics"].get(metric) is not None
                    ):
                        rc = dict(r)
                        rc["metrics"] = dict(r["metrics"])
                        rc["metrics"][metric] = abs(rc["metrics"][metric])
                        rs.append(rc)
                c = cost_to_target(
                    rs, metric, target, cost_keys=("unknowns", "work", "run_s")
                )
                lines.append(
                    f"| {case} | {metric} | {target * 100:g} % | {arm} | "
                    f"{_fmt_cost(c['unknowns'], '{:,.0f}')} | "
                    f"{_fmt_cost(c['work'], '{:.2e}')} | "
                    f"{_fmt_cost(c['run_s'], '{:.0f}')} |"
                )
    (HERE / "data" / phase / "cost_to_target.md").write_text("\n".join(lines) + "\n")


def main_plot(phase):
    FIG.mkdir(exist_ok=True)
    unstable = []
    recs = load(HERE / "data" / phase, unstable=unstable) + load_baselines(phase)
    if not recs:
        return
    cases = sorted({r["case"] for r in recs})
    metrics = ["q_ext_nrms"] + (["enh_peak"] if phase == "B3" else ["q_ext_height"])
    fig, axs = plt.subplots(len(metrics), len(cases), figsize=(4.2 * len(cases), 3.8 * len(metrics)),
                            squeeze=False)  # fmt: skip
    lines = [f"# {phase}: DGTD and baseline arms (generated by plot_bench_ho.py)", "",
             "| case | arm | h [nm] | unknowns | steps | run [s] | " + " | ".join(metrics) + " |",
             "|---|---|---|---|---|---|" + "---|" * len(metrics)]  # fmt: skip
    all_arms = sorted({r["arm"] for r in recs})
    for j, case in enumerate(cases):
        for k, arm in enumerate(all_arms):
            rs = sorted([r for r in recs if r["case"] == case and r["arm"] == arm],
                        key=lambda r: r["cost"]["unknowns"])  # fmt: skip
            if not rs:
                continue
            for i, m in enumerate(metrics):
                y = [abs(r["metrics"].get(m) or np.nan) * 100 for r in rs]
                x = [r["cost"]["unknowns"] for r in rs]
                axs[i, j].loglog(x, y, marker="osD^v<>p*hP"[k % 11], color=f"C{k}" if k < 10 else "#333333",
                                 ls="-" if arm.startswith("dg") else "--", label=label(arm))  # fmt: skip
            for r in rs:
                c = r["cost"]
                vals = " | ".join(f"{abs(r['metrics'].get(m) or np.nan) * 100:.3f} %" for m in metrics)
                lines.append(f"| {case} | {arm} | {r['resolution'] * 1e9:.2f} | {c['unknowns']:,} | "
                             f"{c['steps']} | {c['run_s']:.0f} | {vals} |")  # fmt: skip
        for i, m in enumerate(metrics):
            axs[i, j].set_title(f"{case}: {m}")
            axs[i, j].set_xlabel("field unknowns")
            axs[i, j].set_ylabel("error [%]")
            axs[i, j].grid(True, which="both", alpha=0.2)
    axs[0, 0].legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(FIG / f"{phase}_error_vs_unknowns.png", dpi=130)
    plt.close(fig)
    if unstable:
        lines += [
            "",
            "Excluded (late-time PML growth): "
            + ", ".join(
                f"{r['case']} {r['arm']} h={r['resolution'] * 1e9:.2f}nm (steps={r['cost']['steps']})"
                for r in unstable
            ),
        ]
    (HERE / "data" / phase / "summary.md").write_text("\n".join(lines) + "\n")
    write_cost_to_target(phase, recs, cases)
